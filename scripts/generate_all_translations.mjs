function serializeSection(name, obj, indent = '  ') {
  let lines = [`${indent}${name}: {`];
  for (const [k, v] of Object.entries(obj)) {
    if (typeof v === 'object' && v !== null) {
      lines.push(serializeSection(k, v, indent + '  '));
    } else {
      const cleanVal = String(v).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
      lines.push(`${indent}  ${k}: '${cleanVal}',`);
    }
  }
  // remove trailing comma from last property if desired, or keep it valid TS
  lines.push(`${indent}},`);
  return lines.join('\n');
}

// Languages list
const allLangs = [
  'en', 'hi', 'bn', 'mr', 'te', 'ta', 'gu', 'kn', 'ml', 'pa', 'or', 'as', 
  'ur', 'mai', 'sat', 'ks', 'ne', 'sd', 'kok', 'doi', 'mni', 'brx', 'sa'
];

for (const lang of allLangs) {
  const filePath = join(dir, `${lang}.ts`);
  let content = readFileSync(filePath, 'utf-8');

  // Check if sections already added
  if (content.includes('footer:') && content.includes('onboarding:')) {
    console.log(`⏩ ${lang}.ts already has new sections.`);
    continue;
  }

  // Determine sections data for this language
  let sections = enSections;
  if (lang === 'hi') {
    sections = hiSections;
  } else if (nativeMap[lang]) {
    sections = nativeMap[lang];
  } else {
    // For languages that extend en, we use enSections (or hi if devanagari)
    // Devanagari languages: mai, sa, ne, kok, doi, brx, sat -> can use hi or en
    sections = enSections;
  }

  // Generate serialized code
  let newSectionsCode = '\n';
  for (const [secName, secObj] of Object.entries(sections)) {
    newSectionsCode += `\n${serializeSection(secName, secObj)}`;
  }

  // Insert before the final closing `};`
  const updatedContent = content.replace(/\n\};(\n*)$/, `${newSectionsCode}\n};\n`);
  writeFileSync(filePath, updatedContent, 'utf-8');
  console.log(`✅ Successfully added new sections to ${lang}.ts`);
}

console.log('All language files processed!');
