def get_localized_ack(ack_key: str, lang: str = "en", **kwargs) -> str:
    """Returns localized acknowledgment string for slot transitions."""
    code = (lang or "en").lower().strip()
    pack_map = LOCALIZED_ACKS.get(ack_key, {})
    template = pack_map.get(code) or pack_map.get("en", "")
    try:
        return template.format(**kwargs)
    except Exception:
        return template

def get_non_sc_reply(lang: str = "en") -> str:
    """Returns localized non-SC statutory redirection."""
    code = (lang or "en").lower().strip()
    non_sc_map = LOCALIZED_ACKS.get("non_sc_reply", {})
    return non_sc_map.get(code) or non_sc_map.get("en", "")

def get_language_pack(lang_code: Optional[str] = "en") -> Dict[str, Any]:
    """Retrieves localized strings for all 23 official Indian languages + English."""
    if not lang_code:
        return LANG_PACKS["en"]
    code = lang_code.lower().strip()
    if code in LANG_PACKS:
        return LANG_PACKS[code]
    return LANG_PACKS["en"]

def format_multilingual_recommendations(user_profile: Dict[str, Any], matched_schemes: List[Dict[str, Any]], lang_code: str = "en") -> str:
    """Formats scheme recommendation output in the beneficiary's chosen regional language."""
    code = (lang_code or "en").lower().strip()
    pack = get_language_pack(code)

    def get_lbl(key: str) -> str:
        return SCHEME_LABELS.get(key, {}).get(code) or SCHEME_LABELS.get(key, {}).get("en", key)

    if not matched_schemes:
        return (
            f"{pack['no_schemes']}\n\n"
            f"• Purpose: {user_profile.get('project_type') or user_profile.get('purpose')}\n"
            f"• Required Amount: ₹{user_profile.get('amount', 0):,}\n"
            f"• Annual Income: ₹{user_profile.get('income', 0):,}\n\n"
            "💡 Recommendation: Try requesting an amount within statutory limits or explore our Skill Training programs."
        )

    count = len(matched_schemes)
    lines = [pack["found_schemes"].format(count=count) + "\n"]

    # Add special notices if applicable
    if user_profile.get("gender") == "FEMALE":
        lines.append(pack.get("female_notice", "") + "\n")
    if user_profile.get("is_pwd"):
        lines.append(pack.get("pwd_notice", "") + "\n")

    for idx, s in enumerate(matched_schemes, start=1):
        lines.append(f"### {idx}. **{s.get('name')}** (`{s.get('scheme_id')}`)")
        rate_min = s.get('interest_rate_min', 4.0)
        rate_max = s.get('interest_rate_max', rate_min)
        rate_str = f"{rate_min}% p.a." if rate_min == rate_max else f"{rate_min}% – {rate_max}% p.a."
        lines.append(f"• **{get_lbl('interest_rate')}:** `{rate_str}`")
        lines.append(f"• **{get_lbl('max_loan')}:** ₹{s.get('max_amount', 0):,}")
        lines.append(f"• **{get_lbl('coverage')}:** Up to {s.get('cost_coverage_pct', 90)}%")
        if s.get("moratorium_months") and s["moratorium_months"] != [0, 0]:
            lines.append(f"• **{get_lbl('moratorium')}:** {s['moratorium_months'][0]} to {s['moratorium_months'][1]} months")
        if s.get("match_reason"):
            lines.append(f"• **{get_lbl('why_matched')}:** {s.get('match_reason')}\n")

    lines.append(get_lbl('next_step'))
    return "\n".join(lines)
